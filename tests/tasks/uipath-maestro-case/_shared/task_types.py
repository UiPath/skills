#!/usr/bin/env python3
"""The case task types, as the CLI declares them (MST-15834).

`uip maestro case task-types list --output json` is the declaration: the types an
SDD may declare (`Authorable`), the real task types it may not and that are
authored in Studio Web (`StudioWebOnly`), and names from other layers that are
not task types at all (`NotTaskTypes`, each pointing at the plan type meant).
`task_types.json` beside this file is a snapshot of that command's `Data`, so
the checks run on a CLI that does not carry the command yet.

Every hand-kept copy of the set is checked against it by `test_task_types.py`,
and the guide's not-authorable paragraph is written from it:

    python3 tests/tasks/uipath-maestro-case/_shared/task_types.py --refresh       # snapshot from the CLI
    python3 tests/tasks/uipath-maestro-case/_shared/task_types.py --write-guide   # guide block from the snapshot
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
SNAPSHOT = HERE / "task_types.json"

# Where the generated guide text lives. One constant, so moving it is one edit.
GUIDE = REPO / "skills" / "uipath-planner" / "references" / "case" / "case-design-layers-guide.md"
GUIDE_BLOCK_START = "<!-- task-types:not-authorable:start (generated by tests/tasks/uipath-maestro-case/_shared/task_types.py --write-guide; do not edit) -->"
GUIDE_BLOCK_END = "<!-- task-types:not-authorable:end -->"

COMMAND = ["uip", "maestro", "case", "task-types", "list", "--output", "json"]


LISTS = ("Authorable", "StudioWebOnly", "NotTaskTypes")
VERSIONS = ("WriteSchemaVersion", "ReadSchemaVersion")


def load() -> dict:
    return json.loads(SNAPSHOT.read_text())["Data"]


def lists(data: dict) -> dict:
    """The three task-type lists, the part of the declaration a copy must match exactly.

    The schema versions move on every case-schema floor or pin bump without any
    task type changing, so they are checked for shape only.
    """
    return {key: data[key] for key in LISTS}


def authorable(data: dict | None = None) -> list[str]:
    return [row["Type"] for row in (data or load())["Authorable"]]


def studio_web_only(data: dict | None = None) -> list[str]:
    return [row["Type"] for row in (data or load())["StudioWebOnly"]]


def not_task_types(data: dict | None = None) -> list[dict]:
    return list((data or load())["NotTaskTypes"])


def from_cli() -> dict | None:
    """The command's `Data`, or None when the installed CLI has no such command."""
    try:
        result = subprocess.run(COMMAND, capture_output=True, text=True, timeout=60)
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return None
    text = result.stdout
    start = text.find("{")
    if result.returncode != 0 or start < 0:
        return None
    try:
        payload = json.loads(text[start:])
    except json.JSONDecodeError:
        return None
    if payload.get("Code") != "TaskTypeList":
        return None
    return payload["Data"]


def render_guide_block(data: dict | None = None) -> str:
    """The guide's not-authorable paragraphs: two lists, two reasons."""
    data = data or load()
    real = ", ".join(f"`{t}`" for t in studio_web_only(data))
    wrong = [
        f"- `{row['Spelling']}` → write `{row['PlanType']}` (`{row['Spelling']}` is from `{row['Layer']}`)"
        for row in not_task_types(data)
    ]
    # Every real task type is authorable once Studio Web-only is empty; say nothing then.
    studio = (
        [f"Never author these. Each is a real task type, but an SDD cannot declare it; a person authors it in Studio Web: {real}.", ""]
        if real
        else []
    )
    return "\n".join(
        [
            GUIDE_BLOCK_START,
            *studio,
            "Never write these as a `Type:` either. Each names the same work in another layer, and none is a task type. Write the plan type instead:",
            "",
            *wrong,
            GUIDE_BLOCK_END,
        ]
    )


def guide_block(text: str) -> str | None:
    start = text.find(GUIDE_BLOCK_START)
    end = text.find(GUIDE_BLOCK_END)
    if start < 0 or end < start:
        return None
    return text[start : end + len(GUIDE_BLOCK_END)]


def main(argv: list[str]) -> int:
    if "--refresh" in argv:
        data = from_cli()
        if data is None:
            print(f"FAIL: `{' '.join(COMMAND)}` is not available in the installed CLI", file=sys.stderr)
            return 1
        payload = json.loads(SNAPSHOT.read_text())
        payload["Data"] = data
        SNAPSHOT.write_text(json.dumps(payload, indent=2) + "\n")
        print(f"wrote {SNAPSHOT.relative_to(REPO)}")
    if "--write-guide" in argv:
        text = GUIDE.read_text()
        current = guide_block(text)
        if current is None:
            print(f"FAIL: {GUIDE.relative_to(REPO)} has no task-types block markers", file=sys.stderr)
            return 1
        GUIDE.write_text(text.replace(current, render_guide_block()))
        print(f"wrote the task-types block in {GUIDE.relative_to(REPO)}")
    if not {"--refresh", "--write-guide"} & set(argv):
        print(__doc__)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
